-- Plan 4 — the event-sourced harness core (§1, D-H2 … D-H7).
--
-- `harness_events` is the ONLY history of a harness run. Step provenance, the
-- authorization chain, the live view, the audit certificate and the usage dashboard all
-- become queries over this table. `workflow_steps` degrades to a projection of current
-- status for cheap UI reads; `audit_log` survives only until the legacy runner is deleted.
--
-- Three properties this migration is responsible for:
--   1. Gapless, monotonic `sequence_number` per workflow even when parallel steps append
--      concurrently (D-H3) — hence the append function, not a client-side counter.
--   2. Append-only at the grant level, not by convention (D-H4).
--   3. Org-scoped SELECT so the browser can subscribe over Realtime (D-H5).

/* -------------------------------------------------------------------------- */
/* The stream (D-H2). Columns per the Plan 4 brief; `event_type` carries the   */
/* twelve-value vocabulary of D-H7 (the brief's eleven plus                    */
/* `action_failed_verification`, which is the event that proves the gate).     */
/* -------------------------------------------------------------------------- */

create table public.harness_events (
  id              uuid primary key default gen_random_uuid(),
  workflow_id     uuid not null references public.workflows(id) on delete cascade,
  step_id         uuid references public.workflow_steps(id) on delete set null,
  -- Denormalized so the trace can group by step before step rows exist (and after a
  -- step row is deleted). The loop always knows its step key; the row id it may not.
  step_key        text,
  sequence_number bigint not null,
  event_type      text not null check (event_type in (
                    'step_started',
                    'action_proposed',
                    'action_verified',
                    'action_failed_verification',
                    'action_executed',
                    'observation_received',
                    'step_completed',
                    'step_failed',
                    'human_review_requested',
                    'human_decision',
                    'workflow_paused',
                    'workflow_resumed'
                  )),
  actor           text not null check (actor in ('agent','human','system')),
  payload         jsonb,
  -- Only set on events generated by an LLM call (D-H13). Null elsewhere, which is how
  -- the usage dashboard distinguishes billable events from bookkeeping ones.
  provider_used   text,
  model_used      text,
  -- SHA-256 of the canonical (key-sorted) JSON of whatever input this event consumed.
  -- Tamper-evidence: recomputing it from the cited source data must reproduce it.
  input_hash      text,
  created_at      timestamptz not null default now(),

  -- A sequencing bug must be loud, not silent (D-H3).
  unique (workflow_id, sequence_number)
);

-- The trace reads one workflow in order; the usage dashboard reads by time.
create index on public.harness_events (workflow_id, sequence_number);
create index on public.harness_events (created_at);
create index on public.harness_events (workflow_id, step_key);

/* -------------------------------------------------------------------------- */
/* The append path (D-H3).                                                     */
/*                                                                             */
/* Allocating `max(sequence_number)+1` in application code races: parallel      */
/* steps of the same workflow append concurrently, two readers see the same max */
/* and one insert dies on the unique constraint. Doing it here — under a row    */
/* lock on the parent workflow — serializes appends per workflow while leaving  */
/* different workflows fully concurrent, in one round trip.                     */
/*                                                                             */
/* `security definer` so the function owns the insert; direct INSERT is never   */
/* granted to anon/authenticated (D-H4). Callers pass no sequence number — it   */
/* is not theirs to choose, which is what makes the stream ordered rather than  */
/* merely timestamped.                                                          */
/* -------------------------------------------------------------------------- */

create function public.append_harness_event(
  p_workflow_id   uuid,
  p_event_type    text,
  p_actor         text,
  p_step_id       uuid    default null,
  p_step_key      text    default null,
  p_payload       jsonb   default null,
  p_provider_used text    default null,
  p_model_used    text    default null,
  p_input_hash    text    default null
) returns public.harness_events
language plpgsql volatile security definer set search_path = public as $$
declare
  v_seq bigint;
  v_row public.harness_events;
begin
  -- Serialize appends for THIS workflow only. The lock is released at statement end;
  -- concurrent appends queue behind it rather than colliding on the unique index.
  perform 1 from public.workflows where id = p_workflow_id for update;
  if not found then
    raise exception 'append_harness_event: unknown workflow %', p_workflow_id;
  end if;

  select coalesce(max(sequence_number), 0) + 1
    into v_seq
    from public.harness_events
   where workflow_id = p_workflow_id;

  insert into public.harness_events (
    workflow_id, step_id, step_key, sequence_number, event_type, actor,
    payload, provider_used, model_used, input_hash
  ) values (
    p_workflow_id, p_step_id, p_step_key, v_seq, p_event_type, p_actor,
    p_payload, p_provider_used, p_model_used, p_input_hash
  )
  returning * into v_row;

  return v_row;
end;
$$;

/* -------------------------------------------------------------------------- */
/* RLS (D-H4/D-H5).                                                            */
/*                                                                             */
/* SELECT is org-scoped because Part 7 subscribes from the browser over         */
/* Realtime. There is deliberately NO update or delete policy, and the write    */
/* verbs are revoked outright below: append-only is a missing grant, not a      */
/* convention someone can forget. The service role bypasses RLS for reads and   */
/* reaches inserts through the function above.                                  */
/* -------------------------------------------------------------------------- */

alter table public.harness_events enable row level security;

create policy "org harness events" on public.harness_events for select
  using (exists (select 1 from public.workflows w
                 where w.id = workflow_id and w.org_id = public.auth_org_id()));

-- Belt and braces over the absent policies: even a future policy added by mistake cannot grant
-- a verb that is not granted at the table level.
--
-- TRUNCATE and TRIGGER are revoked as well, and that is not pedantry. Supabase grants ALL on new
-- public tables to `anon`/`authenticated` by default, so this table starts with far more than
-- SELECT. TRUNCATE bypasses RLS entirely and would let a client WIPE the audit trail — an
-- append-only table that anyone can empty is not append-only. TRIGGER would allow attaching a
-- function to the stream. Only SELECT (filtered by the policy above) is left.
revoke insert, update, delete, truncate, trigger, references
  on public.harness_events from anon, authenticated;

-- The function is service-role-only: an API route writes events, a browser never does.
revoke all on function public.append_harness_event(
  uuid, text, text, uuid, text, jsonb, text, text, text
) from anon, authenticated;

/* -------------------------------------------------------------------------- */
/* Realtime (Part 7). Publishing the table lets authenticated clients stream    */
/* inserts under the SELECT policy above — no polling.                          */
/* -------------------------------------------------------------------------- */

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.harness_events;
  end if;
end;
$$;
